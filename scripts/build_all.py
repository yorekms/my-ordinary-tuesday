def story_to_markdown(st, cat_case):
    lines = [
        f"## File № {st['fileNo']} — {st['title']}",
        f"*{st['deck']}*",
        "",
        f"- **Part:** {st['partLabel']}",
        f"- **Companion Episode:** {cat_case['ep']} ({cat_case['duration']}, {cat_case['spokenWords']:,} spoken words)",
        f"- **Looks Like:** {st['looksLike']}",
        f"- **Actually Is:** {st['actuallyIs']}",
        f"- **Cause / Mechanism / Manner:** {st['toeTag']['cause']} | {st['toeTag']['mechanism']} | {st['toeTag']['manner']}",
        f"- **Avoidability:** {st['toeTag']['avoidability']} | **False Reassurance:** {st['toeTag']['falseReassurance']}",
        ""
    ]
    for sec in st['sections']:
        heading_line = f"### {sec['kicker']} — {sec['heading']}" if sec.get('kicker') else f"### {sec['heading']}"
        lines.append(heading_line)
        lines.append("")
        for p in sec.get('paragraphs', []):
            lines.append(p)
            lines.append("")
        for b in sec.get('bullets', []):
            lines.append(f"- {b}")
        if sec.get('bullets'):
            lines.append("")
    lines.append(f"### FIRST 60 SECONDS — {st['survivalCard']['headline']}")
    lines.append(f"*{st['survivalCard']['subhead']}*")
    lines.append("")
    for idx, step in enumerate(st['survivalCard']['steps'], 1):
        lines.append(f"{idx}. **{step['action']}:** {step['detail']}")
    lines.append("")
    lines.append("### Autopsy & Clinical Proof Ledger")
    lines.append("")
    lines.append("| Field | Verified Record |")
    lines.append("| --- | --- |")
    for row in st['ledger']:
        lines.append(f"| **{row['label']}** | {row['value']} |")
    lines.append("")
    lines.append("### Primary Sources & Companion Links")
    lines.append("")
    for src in st['sources']:
        lines.append(f"- **{src['type']}:** [{src['label']}]({src['url']})")
    if cat_case.get('audioDriveUrl'):
        lines.append(f"- **Companion Audio (Google Drive):** [Stream {cat_case['ep']} Audio]({cat_case['audioDriveUrl']})")
    if cat_case.get('audioDirectUrl'):
        lines.append(f"- **Direct 256 kbps .m4a Audio:** [Download / Stream .m4a]({cat_case['audioDirectUrl']})")
    lines.append("")
    return '\n'.join(lines)

